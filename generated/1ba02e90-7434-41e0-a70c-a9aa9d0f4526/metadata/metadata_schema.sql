-- Run this script against the Fabric Warehouse database named Astra_Data_WH.
-- metadata_schema is the Astra metadata schema inside that Warehouse.
IF SCHEMA_ID(N'metadata_schema') IS NULL
    EXEC(N'CREATE SCHEMA metadata_schema');

IF OBJECT_ID(N'metadata_schema.CFG_SOURCE_SYSTEM', N'U') IS NULL
